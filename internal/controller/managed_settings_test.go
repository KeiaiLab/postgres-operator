// settingsWorld 는 D1 values 샤드(primary 0 · replica 1·2)다 — 멤버는 설정 CM 을 마운트하고, auto.conf 에는 메인
// 루프가 남긴 값이 있으며, 렌더 conf 는 투영됐다.
type settingsWorld struct {
	name    string
	cluster *postgresv1alpha1.PostgresCluster
	c       client.Client
	r       *PostgresClusterReconciler
	sim     *confSim
	log     *writeLog
	rec     *events.FakeRecorder
	cm      *corev1.ConfigMap
	pods    []corev1.Pod
	events  []string
	t0      time.Time
}

func newSettingsWorld(t *testing.T, name string) *settingsWorld {
	t.Helper()
	cluster := tunedCluster(name)
	cm := buildConfigMap(cluster, ShardConfigMapName(name, 0), "shard", 0, nil)
	projected := confSettings(cm.Data["postgresql.conf"])
	log := &writeLog{}
	sim := &confSim{log: log, members: map[string]*confMember{}}
	pods := make([]corev1.Pod, 0, settingsMembers)
	for i := range settingsMembers {
		role := statusapi.RoleReplica
		if i == 0 {
			role = statusapi.RolePrimary
		}
		pod := mountConfig(shardMember(name, i, role), cm.Name)
		pods = append(pods, *pod)
		sim.members[pod.Name] = &confMember{auto: mainLoopAuto(), file: maps.Clone(projected)}
	}
	scheme := runtimeScheme(t)
	c := fake.NewClientBuilder().WithScheme(scheme).WithObjects(cm).Build()
	rec := events.NewFakeRecorder(wideEventBuffer)
	r := &PostgresClusterReconciler{Client: c, Scheme: scheme, PromotionPodExecutor: sim, Recorder: rec}
	t.Cleanup(func() { DeleteMetricsFor(runtimeTestNS, name) })
	return &settingsWorld{name: name, cluster: cluster, c: c, r: r, sim: sim, log: log, rec: rec, cm: cm, pods: pods, t0: time.Now()}
}

// own 은 now 의 reconcileAutoConf 한 번이다 — condition 은 w.cluster 에 남는다.
func (w *settingsWorld) own(now time.Time) error {
	err := w.r.reconcileAutoConf(context.Background(), w.cluster, w.pods, now)
	w.events = append(w.events, drainEvents(w.rec)...)
	return err
}

// mustOwn 은 오류 없는 own 이다.
func (w *settingsWorld) mustOwn(t *testing.T, now time.Time) {
	t.Helper()
	if err := w.own(now); err != nil {
		t.Fatalf("reconcileAutoConf: %v", err)
	}
}

// member 는 ordinal 번째 멤버의 설정 파일이다.
func (w *settingsWorld) member(ordinal int) *confMember {
	return w.sim.members[graphMember(w.name, ordinal)]
}

// execs 는 한 파드에 간 exec 기록이다("exec <종류> <파드> …").
func (w *settingsWorld) execs(pod string) []string {
	w.log.mu.Lock()
	defer w.log.mu.Unlock()
	var out []string
	for _, line := range w.log.lines {
		if fields := strings.Fields(line); len(fields) > 2 && fields[0] == "exec" && fields[2] == pod {
			out = append(out, line)
		}
	}
	return out
}

// eventsOf 는 "<type> <reason> " 으로 시작하는 이벤트다.
func (w *settingsWorld) eventsOf(kind, reason string) []string {
	var out []string
	for _, ev := range w.events {
		if strings.HasPrefix(ev, kind+" "+reason+" ") {
			out = append(out, ev)
		}
	}
	return out
}

