// confMember 는 멤버 한 곳의 설정 파일이다 — auto 는 postgresql.auto.conf, file 은 kubelet 이 투영한 렌더 conf 다.
type confMember struct {
	auto       map[string]string
	file       map[string]string
	broken     bool // 렌더 conf 문법 오류(이름 없는 오류 줄)
	down       bool // exec 가 닿지 않는다
	failReload bool
	failReset  string // 이 키의 ALTER SYSTEM RESET 이 실패한다
}

// settingCatalog 는 pg_settings 의 vartype·unit 이다(PG 18).
var settingCatalog = map[string][2]string{
	"wal_keep_size": {"integer", "MB"}, "shared_buffers": {"integer", "8kB"}, "effective_cache_size": {"integer", "8kB"},
	"max_connections": {"integer", ""}, "max_wal_senders": {"integer", ""}, "max_replication_slots": {"integer", ""},
	"port": {"integer", ""}, "wal_level": {"enum", ""}, "hot_standby": {"bool", ""}, "wal_log_hints": {"bool", ""},
}

// askedNames 는 판정 SQL 의 이름 목록이다.
var askedNames = regexp.MustCompile(`f\.name IN \(([^)]*)\)`)

// sqlNames 는 판정 SQL 이 묻는 설정 이름이다.
func sqlNames(sql string) []string {
	m := askedNames.FindStringSubmatch(sql)
	if m == nil {
		return nil
	}
	var out []string
	for raw := range strings.SplitSeq(m[1], ",") {
		out = append(out, strings.Trim(strings.TrimSpace(raw), "'"))
	}
	return out
}

// rows 는 판정 exec 의 답이다 — seqno 순(렌더 conf 뒤 auto.conf): 출처|이름|값 hex|vartype|unit.
func (m *confMember) rows(names []string) string {
	var sb strings.Builder
	row := func(origin, name, value string) {
		kind := settingCatalog[name]
		fmt.Fprintf(&sb, "%s|%s|%s|%s|%s\n", origin, name, hex.EncodeToString([]byte(value)), kind[0], kind[1])
	}
	for _, name := range names {
		if value, ok := m.file[name]; ok {
			row("conf", name, value)
		}
	}
	if m.broken {
		sb.WriteString("conf||||\n")
	}
	for _, name := range names {
		if value, ok := m.auto[name]; ok {
			row("auto", name, value)
		}
	}
	return sb.String()
}

// confSim 은 멤버 postgres 의 pg_file_settings · ALTER SYSTEM RESET · pg_reload_conf 흉내다. 판정 exec 는 SQL 이
// 묻는 이름만 답한다.
type confSim struct {
	mu      sync.Mutex
	log     *writeLog
	members map[string]*confMember
	asked   [][]string
}

func (x *confSim) Exec(_ context.Context, target BackupSidecarTarget, command []string) ([]byte, error) {
	joined := strings.Join(command, " ")
	x.mu.Lock()
	defer x.mu.Unlock()
	m := x.members[target.Pod]
	switch {
	case strings.Contains(joined, autoConfQueryMark):
		x.log.add("exec settings " + target.Pod)
		if m == nil || m.down {
			return nil, fmt.Errorf("exec %s: unreachable", target.Pod)
		}
		names := sqlNames(joined)
		x.asked = append(x.asked, names)
		return []byte(m.rows(names)), nil
	case strings.Contains(joined, "ALTER SYSTEM RESET"):
		key := strings.TrimPrefix(command[len(command)-1], "ALTER SYSTEM RESET ")
		x.log.add("exec reset " + target.Pod + " " + key)
		if m.failReset == key {
			return nil, fmt.Errorf("exec %s: ALTER SYSTEM refused", target.Pod)
		}
		delete(m.auto, key)
		return nil, nil
	case strings.Contains(joined, "pg_reload_conf"):
		x.log.add("exec reload " + target.Pod)
		if m != nil && m.failReload {
			return nil, fmt.Errorf("exec %s: reload refused", target.Pod)
		}
		return []byte("t\n"), nil
	}
	return nil, nil
}

// mountConfig 는 파드가 설정 CM 을 pgConfigMountPath 에 마운트하게 한다(STS 템플릿과 같은 볼륨).
func mountConfig(pod *corev1.Pod, configMap string) *corev1.Pod {
	pod.UID = types.UID(pod.Name + "-uid")
	pod.Spec.Containers = []corev1.Container{{
		Name:         pgContainerName,
		VolumeMounts: []corev1.VolumeMount{{Name: "config", MountPath: pgConfigMountPath, ReadOnly: true}},
	}}
	pod.Spec.Volumes = []corev1.Volume{{Name: "config", VolumeSource: corev1.VolumeSource{
		ConfigMap: &corev1.ConfigMapVolumeSource{LocalObjectReference: corev1.LocalObjectReference{Name: configMap}},
	}}}
	return pod
}

