// quantity 는 시험 수량이다.
func quantity(s string) *resource.Quantity {
	q := resource.MustParse(s)
	return &q
}

// memoryLimit 은 메모리 한 칸의 자원 목록이다.
func memoryLimit(s string) corev1.ResourceList {
	return corev1.ResourceList{corev1.ResourceMemory: resource.MustParse(s)}
}

// tunedCluster 는 D1 values 의 클러스터다 — requests 0.5/3Gi · limits 4/8Gi · walKeepSize 5Gi.
func tunedCluster(name string) *postgresv1alpha1.PostgresCluster {
	cluster, _ := runtimeCluster(name)
	cluster.Spec.Shards.Resources = corev1.ResourceRequirements{
		Requests: corev1.ResourceList{corev1.ResourceCPU: resource.MustParse("500m"), corev1.ResourceMemory: resource.MustParse("3Gi")},
		Limits:   corev1.ResourceList{corev1.ResourceCPU: resource.MustParse("4"), corev1.ResourceMemory: resource.MustParse("8Gi")},
	}
	cluster.Spec.PostgreSQL = &postgresv1alpha1.PostgreSQLSpec{WALKeepSize: quantity("5Gi")}
	return cluster
}

// renderedConf 는 샤드 0 설정 CM 의 postgresql.conf 다.
func renderedConf(cluster *postgresv1alpha1.PostgresCluster) string {
	return buildConfigMap(cluster, ShardConfigMapName(cluster.Name, 0), "shard", 0, nil).Data["postgresql.conf"]
}

// TestPGTuningRender 는 spec 값이 있을 때만 줄이 생기고(hot_standby 뒤 — 기존 8키 무변), limits.memory 에서
// shared_buffers = ÷4 · effective_cache_size = ×3/4, walKeepSize 는 MiB 올림(보존은 줄이지 않는다),
// maxConnections 는 그대로인지 본다.
func TestPGTuningRender(t *testing.T) {
	t.Parallel()
	conns := int32(250)
	cases := []struct {
		name  string
		res   corev1.ResourceRequirements
		pg    *postgresv1alpha1.PostgreSQLSpec
		lines string
	}{
		{name: "unset"},
		{name: "requests only", res: corev1.ResourceRequirements{Requests: memoryLimit("8Gi")}},
		{name: "limits 8Gi", res: corev1.ResourceRequirements{Limits: memoryLimit("8Gi")},
			lines: "shared_buffers = '2048MB'\neffective_cache_size = '6144MB'\n"},
		{name: "limits 1000Mi", res: corev1.ResourceRequirements{Limits: memoryLimit("1000Mi")},
			lines: "shared_buffers = '250MB'\neffective_cache_size = '750MB'\n"},
		{name: "walKeepSize 5Gi", pg: &postgresv1alpha1.PostgreSQLSpec{WALKeepSize: quantity("5Gi")},
			lines: "wal_keep_size = '5120MB'\n"},
		{name: "walKeepSize rounds up", pg: &postgresv1alpha1.PostgreSQLSpec{WALKeepSize: quantity("5G")},
			lines: "wal_keep_size = '4769MB'\n"},
		{name: "walKeepSize zero", pg: &postgresv1alpha1.PostgreSQLSpec{WALKeepSize: quantity("0")}},
		{name: "walKeepSize negative", pg: &postgresv1alpha1.PostgreSQLSpec{WALKeepSize: quantity("-1Gi")}},
		{name: "maxConnections", pg: &postgresv1alpha1.PostgreSQLSpec{MaxConnections: &conns},
			lines: "max_connections = 250\n"},
		{name: "hba only", pg: &postgresv1alpha1.PostgreSQLSpec{HostAuthCIDRs: []string{"10.42.0.0/16"}}},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			cluster := haCluster("tune", postgresv1alpha1.ShardingModeNone)
			cluster.Spec.Shards.Resources, cluster.Spec.PostgreSQL = tc.res, tc.pg
			if got := renderedConf(cluster); got != legacyConf+tc.lines {
				t.Fatalf("postgresql.conf =\n%s\nwant\n%s%s", got, legacyConf, tc.lines)
			}
		})
	}
}

