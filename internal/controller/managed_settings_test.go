// settingsExec 는 SEC1 흉내(pgSim)에 설정 파일 흉내(confSim)를 더한다.
type settingsExec struct {
	*pgSim
	conf *confSim
}

func (x *settingsExec) Exec(ctx context.Context, target BackupSidecarTarget, command []string) ([]byte, error) {
	joined := strings.Join(command, " ")
	if strings.Contains(joined, autoConfQueryMark) || strings.Contains(joined, "ALTER SYSTEM RESET") {
		return x.conf.Exec(ctx, target, command)
	}
	return x.pgSim.Exec(ctx, target, command)
}

